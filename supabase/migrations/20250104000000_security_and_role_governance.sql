-- 1. SECURE HELPER FUNCTIONS FOR ROLE VERIFICATION
create or replace function public.is_admin()
returns boolean as $$
begin
  return exists (
    select 1 from public.users
    where id = auth.uid()
      and role = 'admin'
  );
end;
$$ language plpgsql security definer;

create or replace function public.is_staff_or_admin()
returns boolean as $$
begin
  return exists (
    select 1 from public.users
    where id = auth.uid()
      and role in ('admin', 'faculty', 'organizer')
  );
end;
$$ language plpgsql security definer;

-- 2. PREVENT PRIVILEGE ESCALATION ON PUBLIC.USERS
-- Protects against users modifying their own role to 'admin' or 'faculty'
create or replace function public.prevent_user_role_escalation()
returns trigger as $$
begin
  -- If role is being changed
  if (old.role is distinct from new.role) then
    -- Only allow if the executing user is already an admin
    if not public.is_admin() then
      new.role := old.role; -- Silently preserve original role or raise exception
    end if;
  end if;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists trg_prevent_user_role_escalation on public.users;
create trigger trg_prevent_user_role_escalation
  before update on public.users
  for each row
  execute function public.prevent_user_role_escalation();

