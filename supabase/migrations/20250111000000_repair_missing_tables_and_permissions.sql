-- 6.1 Capacity Limit Verification Trigger (Prevents race conditions / overflow)
create or replace function public.check_registration_capacity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _max int;
  _cur int;
begin
  select coalesce(max_participants, 0), coalesce(current_participants, 0)
    into _max, _cur
    from public.events
    where id = new.event_id
    for update;

  if not found then
    raise exception 'Event not found with ID %', new.event_id;
  end if;

  if _max > 0 and _cur >= _max then
    raise exception 'Event capacity limit reached';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_check_registration_capacity on public.registrations;
create trigger trg_check_registration_capacity
  before insert on public.registrations
  for each row
  execute function public.check_registration_capacity();

-- 6.2 Transactional Participant Count Reconciliation Trigger (Insert & Delete)
create or replace function public.sync_event_participants_count()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _event_id bigint;
begin
  if TG_OP = 'INSERT' then
    _event_id := new.event_id;
  else
    _event_id := old.event_id;
  end if;

  update public.events
  set current_participants = (
    select count(*)::int
    from public.registrations
    where public.registrations.event_id = _event_id
  )
  where id = _event_id;

  return null;
end;
$$;

drop trigger if exists trg_sync_event_participants_count on public.registrations;
create trigger trg_sync_event_participants_count
  after insert or delete on public.registrations
  for each row
  execute function public.sync_event_participants_count();

-- 6.3 Protect Registration user_id and event_id from unauthorized modification
create or replace function public.protect_registration_fields()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_staff_or_admin() then
    if new.user_id is distinct from old.user_id then
      raise exception 'Security Violation: Cannot change registration user_id';
    end if;
    if new.event_id is distinct from old.event_id then
      raise exception 'Security Violation: Cannot change registration event_id';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_protect_registration_fields on public.registrations;
create trigger trg_protect_registration_fields
  before update on public.registrations
  for each row
  execute function public.protect_registration_fields();

-- 6.4 Secure RPC: Increment / Reconcile Event Participants
create or replace function public.increment_participants(event_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _caller uuid;
  _max int;
  _current int;
  _creator uuid;
begin
  _caller := auth.uid();
  if _caller is null then
    raise exception 'Unauthorized: Authentication required';
  end if;

  select coalesce(max_participants, 0), coalesce(current_participants, 0), user_id
    into _max, _current, _creator
    from public.events
    where id = event_id
    for update;

  if not found then
    raise exception 'Event not found with ID %', event_id;
  end if;

  if not (
    public.is_staff_or_admin()
    or (_creator is not null and _creator = _caller)
    or exists (
      select 1 from public.registrations
      where public.registrations.event_id = increment_participants.event_id
        and public.registrations.user_id = _caller
    )
  ) then
    raise exception 'Unauthorized participant count increment: Caller is not registered for this event';
  end if;

  -- Reconcile to actual registration count
  update public.events
  set current_participants = (
    select count(*)::int from public.registrations where public.registrations.event_id = increment_participants.event_id
  )
  where id = event_id;
end;
$$;

-- 6.5 Secure RPC: Decrement / Reconcile Event Participants
create or replace function public.decrement_participants(event_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _caller uuid;
  _event_exists boolean;
begin
  _caller := auth.uid();
  if _caller is null then
    raise exception 'Unauthorized: Authentication required';
  end if;

  select exists(select 1 from public.events where id = event_id) into _event_exists;
  if not _event_exists then
    raise exception 'Event not found with ID %', event_id;
  end if;

  -- Reconcile to actual registration count
  update public.events
  set current_participants = (
    select count(*)::int from public.registrations where public.registrations.event_id = decrement_participants.event_id
  )
  where id = event_id;
end;
$$;

revoke execute on function public.increment_participants(bigint) from anon, public;
revoke execute on function public.decrement_participants(bigint) from anon, public;

grant execute on function public.increment_participants(bigint) to authenticated, service_role;
grant execute on function public.decrement_participants(bigint) to authenticated, service_role;

