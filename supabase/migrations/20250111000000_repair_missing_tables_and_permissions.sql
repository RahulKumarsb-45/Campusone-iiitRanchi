-- 5. ROLE TAMPERING GOVERNANCE TRIGGER ON PUBLIC.USERS
-- ------------------------------------------------------------------------------

create or replace function public.prevent_user_role_escalation()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if TG_OP = 'INSERT' then
    if new.role is not null and lower(trim(new.role)) <> 'student' and not public.is_admin() then
      raise exception 'Security Violation: Self-registered users cannot set non-student role';
    end if;
  elsif TG_OP = 'UPDATE' then
    if new.role is distinct from old.role then
      if not public.is_admin() then
        raise exception 'Security Violation: Only administrators can modify user roles';
      end if;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prevent_user_role_escalation on public.users;
create trigger trg_prevent_user_role_escalation
  before insert or update on public.users
  for each row
  execute function public.prevent_user_role_escalation();

