create or replace function public.is_admin()
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _role text;
begin
  if auth.uid() is null then
    return false;
  end if;
  select role into _role from public.users where id = auth.uid();
  return lower(trim(coalesce(_role, ''))) = 'admin';
end;
$$;

