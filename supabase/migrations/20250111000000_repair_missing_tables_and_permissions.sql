-- 8.12 Users (Profile privacy, ownership protection, and staff directory visibility)
alter table public.users enable row level security;
drop policy if exists "users_anon_select_organizers" on public.users;
drop policy if exists "users_authenticated_select" on public.users;
drop policy if exists "users_insert_policy" on public.users;
drop policy if exists "users_update_policy" on public.users;
drop policy if exists "users_delete_policy" on public.users;

-- Anonymous visitors may only see directory profiles for organizers, faculty, and admins
create policy "users_anon_select_organizers" on public.users
  for select to anon
  using (role in ('admin', 'faculty', 'organizer'));

-- Authenticated members may see their own profile, campus staff/organizers, or all if admin
create policy "users_authenticated_select" on public.users
  for select to authenticated
  using (
    auth.uid() = id
    or role in ('admin', 'faculty', 'organizer')
    or public.is_admin()
  );

-- Users can insert their own profile on signup (strictly with student role); admins can provision
create policy "users_insert_policy" on public.users
  for insert to authenticated
  with check (
    (auth.uid() = id and (role is null or lower(trim(role)) = 'student'))
    or public.is_admin()
  );

-- Users can update their own profile; admins can edit
create policy "users_update_policy" on public.users
  for update to authenticated
  using (auth.uid() = id or public.is_admin())
  with check (auth.uid() = id or public.is_admin());

-- Only administrators can delete a user record
create policy "users_delete_policy" on public.users
  for delete to authenticated
  using (public.is_admin());

