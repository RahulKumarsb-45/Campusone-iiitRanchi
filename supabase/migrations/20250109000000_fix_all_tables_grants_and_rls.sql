-- 7. PARTICIPATION RPC FUNCTIONS (SECURITY DEFINER)
-- ------------------------------------------------------------------------------
-- Allows any registered student to safely increment/decrement participants
-- without requiring direct table UPDATE permission on other users' event rows.

create or replace function public.increment_participants(event_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.events
  set current_participants = coalesce(current_participants, 0) + 1
  where id = event_id;
end;
$$;

create or replace function public.decrement_participants(event_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.events
  set current_participants = greatest(coalesce(current_participants, 0) - 1, 0)
  where id = event_id;
end;
$$;

grant execute on function public.increment_participants(bigint) to anon, authenticated, service_role;
grant execute on function public.decrement_participants(bigint) to anon, authenticated, service_role;

-- ------------------------------------------------------------------------------
-- 8. SECURITY TRIGGERS: ROLE GOVERNANCE & PROFILE SYNC
-- ------------------------------------------------------------------------------

-- Prevent users from escalating their own or others' roles unless they are admins
create or replace function public.prevent_user_role_escalation()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.role is distinct from old.role then
    if not public.is_admin() then
      new.role := old.role; -- Silently preserve existing role
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prevent_user_role_escalation on public.users;
create trigger trg_prevent_user_role_escalation
  before update on public.users
  for each row
  execute function public.prevent_user_role_escalation();

-- Auto-sync new authenticated users to public.users as 'student'
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.users (id, email, name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'name', split_part(coalesce(new.email, 'User'), '@', 1)),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

