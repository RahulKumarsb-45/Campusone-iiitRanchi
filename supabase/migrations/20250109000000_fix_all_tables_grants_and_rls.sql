-- 5. CASE-INSENSITIVE, NON-RECURSIVE ROLE VERIFICATION HELPERS
-- ------------------------------------------------------------------------------
-- Critical: Owned by database superuser (postgres), runs with SECURITY DEFINER
-- and explicit search_path = public, pg_temp. Because public.users SELECT policy
-- checks auth.uid() = id first, recursion never occurs.

create or replace function public.is_admin()
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _role text;
begin
  if auth.uid() is null then
    return false;
  end if;
  select role into _role from public.users where id = auth.uid();
  return lower(trim(coalesce(_role, ''))) = 'admin';
end;
$$;

create or replace function public.is_staff_or_admin()
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _role text;
begin
  if auth.uid() is null then
    return false;
  end if;
  select role into _role from public.users where id = auth.uid();
  return lower(trim(coalesce(_role, ''))) in ('admin', 'faculty', 'organizer');
end;
$$;

grant execute on function public.is_admin() to anon, authenticated, service_role;
grant execute on function public.is_staff_or_admin() to anon, authenticated, service_role;

-- ------------------------------------------------------------------------------
-- 6. TRUSTED OPERATOR BOOTSTRAP FUNCTION
-- ------------------------------------------------------------------------------
-- Allows trusted database administrator to promote any registered auth user to 'admin'.
-- Strictly revoked from public and authenticated clients.

create or replace function public.bootstrap_admin(admin_email text)
returns text
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  target_user_id uuid;
begin
  select id into target_user_id from auth.users where lower(email) = lower(admin_email);
  if target_user_id is null then
    return 'ERROR: User with email ' || admin_email || ' does not exist in auth.users. Please sign up first.';
  end if;

  insert into public.users (id, email, name, role)
  values (target_user_id, admin_email, split_part(admin_email, '@', 1), 'admin')
  on conflict (id) do update set
    role = 'admin';

  return 'SUCCESS: User ' || admin_email || ' (' || target_user_id || ') is now an active administrator.';
end;
$$;

revoke execute on function public.bootstrap_admin(text) from public, anon, authenticated;
grant execute on function public.bootstrap_admin(text) to postgres, service_role;

