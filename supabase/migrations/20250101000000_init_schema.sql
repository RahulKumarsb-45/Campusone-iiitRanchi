-- USERS TABLE
create table if not exists public.users (
  id uuid references auth.users(id) on delete cascade primary key,
  email text not null,
  name text not null,
  role text not null default 'student' check (role in ('student', 'faculty', 'guest', 'organizer', 'admin')),
  department text,
  year text,
  roll_number text,
  position text,
  phone text,
  address text,
  bio text,
  avatar_url text,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;

drop policy if exists "Users are viewable by everyone" on public.users;
create policy "Users are viewable by everyone"
  on public.users for select
  using (true);

drop policy if exists "Users can insert their own profile" on public.users;
create policy "Users can insert their own profile"
  on public.users for insert
  with check (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.users;
create policy "Users can update their own profile"
  on public.users for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- EVENTS TABLE
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  long_description text,
  image text not null default '/placeholder.svg?height=300&width=500',
  date timestamptz not null,
  end_date timestamptz,
  location text not null,
  address text,
  category text not null,
  other_category_details text,
  tags text[] not null default '{}',
  organizer text not null,
  lead_organizer text,
  convener text,
  coordinator text,
  contact_number text,
  registration_link text,
  is_paid boolean not null default false,
  price numeric(10,2),
  max_participants integer not null default 100,
  current_participants integer not null default 0,
  user_id uuid references auth.users(id) on delete set null,
  needs_volunteers boolean not null default false,
  volunteer_roles text[] default '{}',
  created_at timestamptz not null default now()
);

alter table public.events enable row level security;

