create policy "Lost & found items viewable by everyone"
  on public.lost_found_items for select
  using (true);

create policy "Authenticated users can report lost & found"
  on public.lost_found_items for insert
  to authenticated
  with check (auth.uid() = user_id or user_id is null);

create policy "Owners and admins can update lost & found"
  on public.lost_found_items for update
  to authenticated
  using (auth.uid() = user_id or public.is_staff_or_admin())
  with check (auth.uid() = user_id or public.is_staff_or_admin());

create policy "Owners and admins can delete lost & found"
  on public.lost_found_items for delete
  to authenticated
  using (auth.uid() = user_id or public.is_staff_or_admin());

